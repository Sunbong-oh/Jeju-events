PATTERNS = [(re.compile(re.escape(k)), name, lat, lng) for k, name, lat, lng in PLACES]


def locate(text):
    """(표시명, 위도, 경도) 또는 None. 글에서 가장 구체적인 장소를 고른다."""
    for pat, name, lat, lng in PATTERNS:
        if pat.search(text):
            return name, lat, lng
    return None


def km_between(a_lat, a_lng, b_lat, b_lng):
    r = 6371
    p1, p2 = math.radians(a_lat), math.radians(b_lat)
    dp, dl = p2 - p1, math.radians(b_lng - a_lng)
    h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(math.sqrt(h))


def where(ev, home):
    """{'area': 지역명, 'km': 직선거리} 또는 {} — home은 {'lat','lng'}."""
    # 모든 글귀를 합쳐서 찾으면 PLACES 순서상 가장 구체적인 장소가 먼저 걸린다
    # 상세 페이지에서 읽은 실제 장소(place)가 있으면 그것부터 본다
    loc = locate(ev.get("place") or "") or locate(
        " ".join(str(ev.get(f) or "") for f in ("info", "title", "snippet", "post_title")))
    if not loc:
        return {}
    if not home:  # 집 위치를 모르면 지역 이름만
        return {"area": loc[0]}
    return {"area": loc[0], "km": round(km_between(home["lat"], home["lng"], loc[1], loc[2]))}


def zone(area):
    """'city'(제주시 동 지역) / 'out'(제주시 읍면·서귀포시) / None(위치 모름)."""
    if not area:
        return None
    if area.startswith("제주시") and not re.search(r"[읍면](?:\s|$)", area):
        return "city"
    return "out"
